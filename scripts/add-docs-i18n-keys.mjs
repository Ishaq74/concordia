for (const locale of locales) {
  const filePath = path.join(i18nDir, `${locale}.json`);
  const json = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  // Merge common keys
  if (!json.docs) json.docs = {};
  if (!json.docs.common) json.docs.common = {};
  Object.assign(json.docs.common, commonKeys[locale]);

  // Merge page keys into docs.pages
  if (!json.docs.pages) json.docs.pages = {};
  Object.assign(json.docs.pages, pageKeys[locale]);

  fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
  
  const totalKeys = JSON.stringify(json).match(/"[^"]+"\s*:/g)?.length ?? 0;
  console.log(`${locale}.json: ~${totalKeys} keys`);
}

