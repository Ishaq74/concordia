function addExtraCommonKeys() {
  for (const locale of ['fr', 'en', 'es', 'ar']) {
    const filePath = path.join(I18N_DIR, `${locale}.json`);
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    let added = 0;
    for (const [key, value] of Object.entries(EXTRA_COMMON[locale])) {
      if (!data.docs.common[key]) {
        data.docs.common[key] = value;
        added++;
      }
    }
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
    console.log(`  ${locale}.json: +${added} extra common keys`);
  }
}

